/**
 * What a nomination is judged on, as one plain paragraph: the form shows it
 * under each name in its list and under the chosen one, so that an applicant
 * remembers where they are applying. The developers' mockup of that list
 * takes the desktop wording.
 */
export function nominationNote(nomination: Nomination): string {
  const { criteria } = nomination;
  const text = typeof criteria === "string" ? criteria : criteria.desktop;
  return text.replace(/[|^\n]/g, " ");
}
